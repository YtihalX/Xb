"""Curve data for the cetz plots in ../slides (u_n(r), f_n(p), E_n, f_n(0), colours).

Same inputs as figs.py. Run from code/:
    uv run --no-project --with numpy --with scipy --with matplotlib python typst_data.py
Writes ../slides/data.typ.
"""
from pathlib import Path

import numpy as np
from matplotlib import colormaps

from cornell import G, M_TH, MB_QUARK, V0_FIT, form_factor, solve_cornell

HBARC = 0.1973269804
OUT = Path(__file__).resolve().parent.parent / "slides" / "data.typ"
N_STATES = 7
R_STEP, R_MAX = 0.02, 3.0  # fm
P_STEP, P_MAX = 0.02, 2.5  # GeV

r, dr, eps, u = solve_cornell(nstates=N_STATES)
e_bare = 2 * MB_QUARK + eps - M_TH + V0_FIT  # E_n^(0) + V_0 [GeV]
f0 = form_factor([0.0], r, dr, u).real[0]  # f_n(0) [GeV^-3/2]

r_fm = np.arange(round(R_MAX / R_STEP) + 1) * R_STEP
r_grid = np.concatenate(([0.0], r))  # u_n(0) = 0
u_samples = [np.interp(r_fm / HBARC, r_grid, np.concatenate(([0.0], u[:, n]))) for n in range(N_STATES)]
p_gev = np.arange(round(P_MAX / P_STEP) + 1) * P_STEP
f_samples = form_factor(p_gev, r, dr, u).real.T
colours = colormaps["viridis"](np.linspace(0.0, 0.9, N_STATES))


def number(x, digits):
    s = f"{x:.{digits}f}"
    return "0" if float(s) == 0 else s


def array(values, digits, per_line=12, indent="  "):
    items = [number(v, digits) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "(\n" + "".join(f"{indent}  {line},\n" for line in lines) + f"{indent})"


def nested(curves, digits):
    return "(\n" + "".join(f"  {array(c, digits)},\n" for c in curves) + ")"


hex_colours = ", ".join(f'rgb("#{int(255 * c[0]):02x}{int(255 * c[1]):02x}{int(255 * c[2]):02x}")' for c in colours)
OUT.write_text(f"""// Generated by code/typst_data.py from code/cornell.py; do not edit by hand.
// Bare P-wave Cornell tower: m_b = {MB_QUARK:.4f} GeV, lattice sigma and gamma, V_0 = {V0_FIT * 1e3:.1f} MeV.
// "@typstyle off" keeps each array as laid out here; typstyle would put one number per line.

// viridis samples used for curve n = 1..{N_STATES} (as in code/figs.py)
// @typstyle off
#let curve-colours = ({hex_colours})

// coupling g [GeV], bare energies E_n^(0) + V_0 [GeV] and f_n(0) [GeV^(-3/2)], n = 1..{N_STATES}
#let cornell-g = {G:.6f}
// @typstyle off
#let cornell-e-bare = ({", ".join(number(e, 6) for e in e_bare)})
// @typstyle off
#let cornell-f0 = ({", ".join(number(f, 4) for f in f0)})

// u_n(r) = r R_(1n)(r) [GeV^(1/2)] at r = 0, {R_STEP}, ..., {R_MAX} fm
#let un-r-step = {R_STEP}
// @typstyle off
#let un-values = {nested(u_samples, 4)}

// f_n(p) [GeV^(-3/2)] at p = 0, {P_STEP}, ..., {P_MAX} GeV
#let fn-p-step = {P_STEP}
// @typstyle off
#let fn-values = {nested(f_samples, 3)}
""")
print(f"wrote {OUT}: {len(r_fm)} r points, {len(p_gev)} p points, {N_STATES} states")
print("E_bare [MeV]:", np.round(e_bare * 1e3, 1), " f_n(0):", np.round(f0, 2), " g [MeV]:", round(G * 1e3, 2))
